//go:build ignore

// gen-accessors generates nil-safe Get methods for the pointer fields of the
// API types, in the style of go-github. Run it with:
//
//	go generate ./...
//
// It writes accessors.go, which must not be edited by hand.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const outputFile = "accessors.go"

// types lists the structs that get accessors.
var types = map[string]bool{
	"Data":  true,
	"Feed":  true,
	"Group": true,
	"Owner": true,
}

// zeroValues maps the basic types used in pointer fields to their zero values.
var zeroValues = map[string]string{
	"bool":    "false",
	"float64": "0",
	"int":     "0",
	"int64":   "0",
	"string":  `""`,
}

type accessor struct {
	typeName  string
	fieldName string
	fieldType string // the type the field points to, e.g. "string" or "Owner"
	basic     bool   // true for basic types, false for struct pointers
}

func main() {
	files, err := filepath.Glob("*.go")
	if err != nil {
		log.Fatal(err)
	}

	fset := token.NewFileSet()
	var accessors []accessor

	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") || name == outputFile || name == "gen-accessors.go" {
			continue
		}

		file, err := parser.ParseFile(fset, name, nil, 0)
		if err != nil {
			log.Fatal(err)
		}

		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				st, ok := ts.Type.(*ast.StructType)
				if !ok || !types[ts.Name.Name] {
					continue
				}
				for _, field := range st.Fields.List {
					star, ok := field.Type.(*ast.StarExpr)
					if !ok {
						continue // only pointer fields get accessors
					}
					ident, ok := star.X.(*ast.Ident)
					if !ok {
						log.Fatalf("%s: unsupported field type in %s", fset.Position(field.Pos()), ts.Name.Name)
					}
					_, basic := zeroValues[ident.Name]
					if !basic && !types[ident.Name] {
						log.Fatalf("%s: no zero value for *%s in %s", fset.Position(field.Pos()), ident.Name, ts.Name.Name)
					}
					for _, fieldName := range field.Names {
						accessors = append(accessors, accessor{
							typeName:  ts.Name.Name,
							fieldName: fieldName.Name,
							fieldType: ident.Name,
							basic:     basic,
						})
					}
				}
			}
		}
	}

	sort.Slice(accessors, func(i, j int) bool {
		if accessors[i].typeName != accessors[j].typeName {
			return accessors[i].typeName < accessors[j].typeName
		}
		return accessors[i].fieldName < accessors[j].fieldName
	})

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen-accessors.go; DO NOT EDIT.\n")
	buf.WriteString("// Run go generate ./... to regenerate.\n\n")
	buf.WriteString("package adafruitio\n")

	for _, a := range accessors {
		recv := strings.ToLower(a.typeName[:1])
		if a.basic {
			fmt.Fprintf(&buf, `
// Get%[3]s returns the %[3]s field if it's non-nil, zero value otherwise.
func (%[1]s *%[2]s) Get%[3]s() %[4]s {
	if %[1]s == nil || %[1]s.%[3]s == nil {
		return %[5]s
	}
	return *%[1]s.%[3]s
}
`, recv, a.typeName, a.fieldName, a.fieldType, zeroValues[a.fieldType])
		} else {
			fmt.Fprintf(&buf, `
// Get%[3]s returns the %[3]s field.
func (%[1]s *%[2]s) Get%[3]s() *%[4]s {
	if %[1]s == nil {
		return nil
	}
	return %[1]s.%[3]s
}
`, recv, a.typeName, a.fieldName, a.fieldType)
		}
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(outputFile, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
